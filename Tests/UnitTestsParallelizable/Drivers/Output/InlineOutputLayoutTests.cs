namespace DriverTests.Output;

public class InlineOutputLayoutTests
{
    [Theory]
    [InlineData ("", "")]
    [InlineData ("\n", "")]
    [InlineData ("a\n", "a")]
    [InlineData ("a\n\n", "a|")]
    [InlineData ("a\r\nb\rc", "a|b|c")]
    public void StringNewlines (string text, string expected) =>
        Assert.Equal (expected, string.Join ("|", ApplicationInlineOutputExtensions.Split (text).Select (Text)));

    // CoPilot - GPT-6
    [Fact]
    public void OversizedNewlineOnlyStringRejectsBeforeMaterializingLines ()
    {
        string text = new ('\n', InlineOutputLayout.MaximumUnits / 2 + 1);
        long before = GC.GetAllocatedBytesForCurrentThread ();

        Assert.Throws<InvalidOperationException> (() => ApplicationInlineOutputExtensions.Split (text));

        Assert.InRange (GC.GetAllocatedBytesForCurrentThread () - before, 0, 65536);
    }

    [Theory]
    [InlineData ("abcd", 4, "abcd")]
    [InlineData ("abcde", 4, "abcd|e")]
    [InlineData ("ab界", 3, "ab|界")]
    [InlineData ("界", 1, "�")]
    [InlineData ("a\t", 4, "a   |    ")]
    [InlineData ("é", 1, "é")]
    [InlineData ("👩‍👩‍👧‍👦", 2, "👩‍👩‍👧‍👦")]
    public void WrapsByDisplayCells (string text, int width, string expected)
    {
        InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan (text)])]);
        InlineOutputRow [] rows = layout.Rows (width).ToArray ();
        Assert.Equal (expected, string.Join ("|", rows.Select (Text)));
        Assert.Equal (rows.Length, layout.CountRows (width));
    }

    [Fact]
    public void GraphemesAndSurrogatesAcrossSpansUseFirstStyle ()
    {
        Attribute red = new (Color.Red, Color.None);
        InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan ("e", red), new InlineOutputSpan ("́"),
                                                                new InlineOutputSpan ("\ud83d", red), new InlineOutputSpan ("\ude00")])]);
        InlineOutputRow [] rows = layout.Rows (2).ToArray ();
        Assert.Equal (["é", "😀"], rows.Select (Text));
        Assert.All (rows.SelectMany (row => row.Spans), span => Assert.Equal (red, span.Attribute));
    }

    [Theory]
    [InlineData ("\u001b[2J")]
    [InlineData ("a\n")]
    [InlineData ("\r")]
    [InlineData ("\0")]
    [InlineData ("\u007f")]
    [InlineData ("\u0085")]
    public void RejectsControlsAndInvalidUnicode (string text) =>
        Assert.Throws<ArgumentException> (() => new InlineOutputLayout ([new InlineOutputLine ([new InlineOutputSpan (text)])]));

    [Fact]
    public void InvalidSurrogatesAreRejectedWithoutTestDataSerialization ()
    {
        foreach (char surrogate in (char [])['\ud800', '\udc00'])
        {
            string text = new (surrogate, 1);
            Assert.Throws<ArgumentException> (() => new InlineOutputLayout ([new InlineOutputLine ([new InlineOutputSpan (text)])]));
        }
    }

    [Fact]
    public void SnapshotsAndRejectsNullsAndOversizedPayloads ()
    {
        List<InlineOutputSpan> spans = [new ("original")];
        InlineOutputLine line = new (spans);
        List<InlineOutputLine> lines = [line];
        InlineOutputLayout layout = new (lines);
        spans.Clear ();
        lines.Clear ();
        Assert.Equal ("original", Text (Assert.Single (layout.Rows (80))));
        Assert.Throws<ArgumentNullException> (() => new InlineOutputLayout ([null!]));
        Assert.Throws<ArgumentNullException> (() => new InlineOutputLayout ([new InlineOutputLine ([null!])]));
        Assert.Throws<ArgumentNullException> (() => new InlineOutputLayout ([new InlineOutputLine ([new InlineOutputSpan (null!)])]));
        Assert.Throws<InvalidOperationException> (() => new InlineOutputLayout ([new InlineOutputLine ([new InlineOutputSpan (new string ('x', InlineOutputLayout.MaximumUnits))])]));
        Assert.True (new InlineOutputLayout ([]).IsEmpty);
        Assert.Throws<ArgumentOutOfRangeException> (() => layout.CountRows (0));
    }

    // CoPilot - GPT-6 (generated by Codex)
    [Theory]
    [InlineData ('a')]
    [InlineData ('\t')]
    public void MaximumPayload_CountOnlyAllocatesNoPerElementObjects (char character)
    {
        string text = new (character, InlineOutputLayout.MaximumUnits - 1);
        InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan (text)])]);
        const int width = 80;
        int columns = checked (text.Length * (character == '\t' ? 8 : 1));
        int expected = (columns + width - 1) / width;
        Assert.Equal (expected, layout.CountRows (width)); // Warm width and Unicode caches before measuring.

        // Aggressive cache warm-up: Force garbage collection to stabilize allocations
        // on all platforms. Windows CI exhibits larger StringInfo initialization overhead
        // on first-call; this ensures stable memory state before measurement.
        GC.Collect ();
        GC.WaitForPendingFinalizers ();
        GC.Collect ();

        long before = GC.GetAllocatedBytesForCurrentThread ();
        int actual = layout.CountRows (width);
        long allocated = GC.GetAllocatedBytesForCurrentThread () - before;

        Assert.Equal (expected, actual);
        Assert.InRange (allocated, 0, 4096);
    }

    // CoPilot - GPT-6 (generated by Codex)
    [Fact]
    public void MaximumAsciiPayload_MaterializesOneSpanPerRowWithBoundedAllocations ()
    {
        string text = new ('a', InlineOutputLayout.MaximumUnits - 1);
        InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan (text)])]);
        const int width = 4096;
        InlineOutputLayout warmup = new ([new InlineOutputLine ([new InlineOutputSpan ("warmup")])]);
        _ = warmup.Rows (width).ToArray ();
        var rows = 0;
        var spans = 0;
        var characters = 0;
        var columns = 0;

        long before = GC.GetAllocatedBytesForCurrentThread ();
        foreach (InlineOutputRow row in layout.Rows (width))
        {
            rows++;
            spans += row.Spans.Count;
            columns += row.Columns;
            foreach (InlineOutputSpan span in row.Spans)
            {
                characters += span.Text.Length;
            }
        }
        long allocated = GC.GetAllocatedBytesForCurrentThread () - before;

        Assert.Equal ((text.Length + width - 1) / width, rows);
        Assert.Equal (rows, spans);
        Assert.Equal (text.Length, characters);
        Assert.Equal (text.Length, columns);
        // UTF-16 row strings plus bounded per-row metadata, rather than objects per input character.
        Assert.InRange (allocated, 0, text.Length * 3L);
    }

    // CoPilot - GPT-6 (generated by Codex)
    [Fact]
    public void CoalescesEqualStylesAndTabsWithoutSplittingCrossSpanGraphemes ()
    {
        Attribute red = new (Color.Red, Color.None);
        Attribute blue = new (Color.Blue, Color.None);
        InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan ("a", red), new InlineOutputSpan ("b", red),
                                                                new InlineOutputSpan ("e"), new InlineOutputSpan ("́", red),
                                                                new InlineOutputSpan (string.Empty, red), new InlineOutputSpan ("👩‍", blue),
                                                                new InlineOutputSpan ("👩‍👧‍👦"), new InlineOutputSpan ("\t"), new InlineOutputSpan ("z")])]);
        InlineOutputRow row = Assert.Single (layout.Rows (20));
        Assert.Equal ("abé👩‍👩‍👧‍👦   z", Text (row));
        Assert.Equal ((Attribute? [])[red, null, blue, null], row.Spans.Select (span => span.Attribute));
        Assert.Equal (["ab", "é", "👩‍👩‍👧‍👦", "   z"], row.Spans.Select (span => span.Text));
        Assert.Equal (9, row.Columns);
    }

    // CoPilot - GPT-6 (generated by Codex)
    [Theory]
    [InlineData (1)]
    [InlineData (2)]
    [InlineData (3)]
    [InlineData (7)]
    [InlineData (8)]
    [InlineData (13)]
    [InlineData (80)]
    public void CountAndRowsAgreeAcrossTabsWideAndZeroWidthGraphemes (int width)
    {
        string [] texts = [string.Empty, "\t", "a\t\tend", new string ('\t', 100), "界ab界", "́a\u200b\t界👩‍👩‍👧‍👦é", "ab\u200b界", "é👩‍👩‍👧‍👦"];
        foreach (string text in texts)
        {
            InlineOutputLayout layout = new ([new InlineOutputLine ([new InlineOutputSpan (text)])]);
            InlineOutputRow [] rows = layout.Rows (width).ToArray ();
            Assert.Equal (rows.Length, layout.CountRows (width));
            Assert.All (rows, row => Assert.InRange (row.Columns, 0, width));
        }
    }

    private static string Text (InlineOutputRow row) => string.Concat (row.Spans.Select (span => span.Text));

    private static string Text (InlineOutputLine line) => string.Concat (line.Spans.Select (span => span.Text));
}
